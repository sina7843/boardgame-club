#!/usr/bin/env node
// Syncs the BGV design system from design/system into packages/ui/src/bgv (run after a design-system update).
// tokens.css / bundle.css are copied byte-identical; bundle.js (classic script over window.React) becomes the
// ES module bgv.js with the same code, and index.d.ts becomes its type declaration.
import { readFileSync, writeFileSync, copyFileSync, mkdirSync } from 'node:fs';

const src = 'design/system';
const out = 'packages/ui/src/bgv';
mkdirSync(`${out}/reference`, { recursive: true });
copyFileSync(`${src}/tokens.css`, `${out}/tokens.css`);
copyFileSync(`${src}/components/bundle.css`, `${out}/bundle.css`);
copyFileSync(`${src}/components/bundle.js`, `${out}/reference/bundle.js`);
copyFileSync(`${src}/components/index.d.ts`, `${out}/reference/index.d.ts`);

const js = readFileSync(`${src}/components/bundle.js`, 'utf8');
const open = "(function () {\n  'use strict';\n  var React = window.React;";
const close = '  window.Bgv = Bgv;\n})();';
if (!js.includes(open) || !js.includes(close)) throw new Error('bgv-sync: bundle.js wrapper changed; update this script');
let body = js
  .replace(open, "import * as React from 'react';\n{")
  .replace("  if (!React) { throw new Error('Bgv: window.React is required before bundle.js'); }\n", '')
  .replace(close, '  _bgv = Bgv;\n}');
// Local fix (DECISIONS.md, to report upstream): OtpField took one digit per box (maxLength 1), so SMS one-time-code
// autofill and pasting the whole code only filled the first box. A multi-digit value now spreads over the boxes.
const otpChange = 'value: fa(d), onChange: function (e) { set(i, norm(e.target.value).slice(-1)); },';
const otpMax = "autoComplete: i === 0 ? 'one-time-code' : 'off', maxLength: 1,";
const otpAnchor = '    var digits = norm(code);\n    return h(\'div\', R(p, [\'length\'';
if (!body.includes(otpChange) || !body.includes(otpMax) || !body.includes(otpAnchor)) throw new Error('bgv-sync: OtpField changed; review the local fix');
body = body
  .replace(otpChange, 'value: fa(d), onChange: function (e) { var v = norm(e.target.value); if (v.length > 1) { fill(i, v); } else { set(i, v.slice(-1)); } },')
  .replace(otpMax, "autoComplete: i === 0 ? 'one-time-code' : 'off',")
  .replace(otpAnchor, '    function fill(i, v) { var arr = norm(code).split(\'\'); while (arr.length < len) { arr.push(\'\'); } for (var k = 0; k < v.length && i + k < len; k++) { arr[i + k] = v[k]; } var next = arr.join(\'\').slice(0, len); _s[1](next); if (p.onChange) { p.onChange(next); } var to = refs.current[Math.min(i + v.length, len - 1)]; if (to) { to.focus(); } if (next.length === len && p.onComplete) { p.onComplete(next); } }\n' + otpAnchor);
writeFileSync(`${out}/bgv.js`, `// GENERATED by scripts/bgv-sync.mjs from design/system/components/bundle.js. Do not edit.\n/* eslint-disable */\nlet _bgv;\n${body}\nexport default _bgv;\n`);

const dts = readFileSync(`${src}/components/index.d.ts`, 'utf8').replace(/\ndeclare global \{[^\n]*\}\n?/, '\n');
writeFileSync(`${out}/bgv.d.ts`, `// GENERATED by scripts/bgv-sync.mjs from design/system/components/index.d.ts. Do not edit.\n${dts}`);
console.log('bgv-sync: packages/ui/src/bgv updated');
